-- 1.2 Rol Kontrol Fonksiyonu (SECURITY DEFINER)
-- Belirli bir kullanıcının belirli bir role sahip olup olmadığını kontrol eder.
-- RLS politikalarında recursive sorgu sorununu önlemek için SECURITY DEFINER kullanılır.
CREATE OR REPLACE FUNCTION public.has_role(_user_id uuid, _role app_role)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.user_roles
    WHERE user_id = _user_id AND role = _role
  )
$$;


-- 1.3 Personel Kontrol Fonksiyonu (SECURITY DEFINER)
-- Kullanıcının user_roles tablosunda herhangi bir kaydı olup olmadığını kontrol eder.
CREATE OR REPLACE FUNCTION public.is_staff(_user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.user_roles
    WHERE user_id = _user_id
  )
$$;


-- 1.4 updated_at Otomatik Güncelleme Trigger Fonksiyonu
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;


