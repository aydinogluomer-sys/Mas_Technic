lines.push("|---|---|---|---|");
for (const phase of [...perPhase.keys()].sort()) {
  const entry = perPhase.get(phase);
  lines.push(
    `| Phase ${phase} | ${entry.primary} | ${entry.ranges.length ? entry.ranges.join(", ") : "—"} | ${
      entry.sharedRanges?.length ? `${entry.sharedRanges.join(", ")} (${entry.shared} IDs)` : "—"
    } |`,
  );
}
lines.push("");
lines.push("## Full per-ID matrix (every requirement ID 1–739, exactly once)");
lines.push("");
lines.push("| ID | Phase | Theme |");
lines.push("|---|---|---|");
for (const [from, to, phase, secondary, theme] of RANGES) {
  for (let id = from; id <= to; id += 1) {
    lines.push(`| ${id} | Phase ${phase} | ${fmtTheme(secondary, theme)} |`);
  }
}
lines.push("");
lines.push("## Coverage assertion (machine-checkable)");
lines.push("");
lines.push("```text");
lines.push(`TOTAL_IDS: ${TOTAL}`);
lines.push(`MAPPED: ${owner.size}`);
lines.push(`UNMAPPED: ${gaps.length}`);
lines.push(`DUPLICATES: ${duplicates.length}`);
lines.push(`OUT_OF_RANGE: ${outOfRange.length}`);
lines.push(`GAPS: [${gaps.join(", ")}]`);
lines.push(`DUPLICATE_IDS: [${duplicates.join(", ")}]`);
lines.push(`RANGE_COUNT: ${RANGES.length}`);
lines.push(`SUM_OF_RANGE_LENGTHS: ${RANGES.reduce((total, [from, to]) => total + (to - from + 1), 0)}`);
lines.push(`ASSERTION: ${gaps.length === 0 && duplicates.length === 0 && owner.size === TOTAL ? "PASS" : "FAIL"}`);
lines.push("```");
lines.push("");

writeFileSync(OUT, `${lines.join("\n")}\n`, "utf8");

