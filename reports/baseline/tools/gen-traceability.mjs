// --- coverage proof -------------------------------------------------------
const owner = new Map();
const duplicates = [];
for (const [from, to, phase] of RANGES) {
  for (let id = from; id <= to; id += 1) {
    if (owner.has(id)) duplicates.push(id);
    else owner.set(id, phase);
  }
}
const gaps = [];
for (let id = 1; id <= TOTAL; id += 1) if (!owner.has(id)) gaps.push(id);
const outOfRange = [...owner.keys()].filter((id) => id < 1 || id > TOTAL);

// --- per-phase rollup -----------------------------------------------------
const perPhase = new Map();
for (const [from, to, phase, secondary] of RANGES) {
  const count = to - from + 1;
  const entry = perPhase.get(phase) ?? { primary: 0, ranges: [] };
  entry.primary += count;
  entry.ranges.push(from === to ? `${from}` : `${from}–${to}`);
  perPhase.set(phase, entry);
  for (const extra of secondary) {
    const secondaryEntry = perPhase.get(extra) ?? { primary: 0, ranges: [], shared: 0, sharedRanges: [] };
    secondaryEntry.shared = (secondaryEntry.shared ?? 0) + count;
    secondaryEntry.sharedRanges = [...(secondaryEntry.sharedRanges ?? []), from === to ? `${from}` : `${from}–${to}`];
    perPhase.set(extra, secondaryEntry);
  }
}

const fmtRange = (from, to) => (from === to ? `${from}` : `${from}–${to}`);
const fmtTheme = (secondary, theme) =>
  secondary.length ? `${theme} — SHARED, secondary owner${secondary.length > 1 ? "s" : ""}: Phase ${secondary.join(" + Phase ")}` : theme;

