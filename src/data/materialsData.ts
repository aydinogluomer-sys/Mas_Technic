/** Where a material's numeric properties come from (T03). */
export interface MaterialSource {
  /** Standard, datasheet or certificate the figures were read from. */
  document: string;
  url?: string;
  /** ISO date the figures were checked against the document. */
  checkedAt: string;
  /** Who reviewed the figures (owner input O05). */
  reviewedBy: string;
}

/** E1 — where ONE published property comes from. */
export interface PropertySource {
  /** Datasheet title as printed. */
  document: string;
  /** Producer or body that issued it. */
  publisher: string;
  url: string;
  /** Revision / date printed on the document, or `null` when it shows none. */
  version: string | null;
  /** Page, table or section the value was read from. */
  locator: string;
  /** Test condition, temper, form and whether the value is typical, a minimum or a range. */
  condition: string;
  /** ISO date the value was read from the document. */
  checkedAt: string;
}

export type SourcedProperty = "density" | "tensileStrength" | "hardness" | "thermalConductivity" | "maxTemperature";

export interface Material {
  id: string;
  name: string;
  category: "metal" | "plastic" | "composite";
  subcategory: string;
  /** Grade and temper / condition the figures refer to, e.g. `6061-T6`.
      `null` when the record names a polymer or laminate family, not a grade. */
  gradeTemper: string | null;
  /** Semi-finished form the figures refer to (levha, çubuk, …). `null` = not stated. */
  productForm: string | null;
  /** `null` = the numeric properties below are unsourced: the public pages print
      "Veri doğrulanmadı" for them and sort them last (never as 0). */
  source: MaterialSource | null;
  /** Test conditions the figures depend on — temperature, temper, fibre
      direction, polymer conditioning. Shown beside the property. */
  propertyConditions: string;
  /** E1 — per-property provenance. A property listed here is published with
      its source; every other numeric property prints "Veri doğrulanmadı".
      (A whole-record `source` still publishes every property, T03.) */
  propertySources?: Partial<Record<SourcedProperty, PropertySource>>;
  /** How a sourced value reads when it is a range, a bound or qualified
      (`540–750`, `≥ 895 (min.)`, `125 (HDT)`); the number is what sorts. */
  propertyText?: Partial<Record<SourcedProperty, string>>;
  description: string;
  density: number;
  tensileStrength: number;
  hardness: string;
  maxTemperature: number;
  thermalConductivity: number;
  /** INTERNAL ONLY (T03). An undocumented 1–5 score; not rendered on any
      public page and not used for sorting until a documented rubric exists. */
  machinability: number;
  /** INTERNAL ONLY (T03). Same rule as `machinability`. */
  corrosionResistance: number;
  /** INTERNAL ONLY (T03). Price is discussed in the RFQ, never published. */
  priceCategory: "low" | "medium" | "high";
  applications: string[];
  advantages: string[];
  limitations: string[];
  isPopular?: boolean;
}

